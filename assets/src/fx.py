FLAME_DRAWN = {'n': FLAME_N, 'ne': FLAME_NE, 'e': FLAME_E}


def flame(direction, phase):
    if direction in FLAME_DRAWN:
        return art(FLAME_DRAWN[direction][phase], FLAME_W, FLAME_H,
                   'flame/%s%d' % (direction, phase))
    src, do_flip, do_mirror = DERIVED[direction]
    img = art(FLAME_DRAWN[src][phase], FLAME_W, FLAME_H,
              'flame/%s%d' % (src, phase))
    if do_flip:
        img = flip(img)
    if do_mirror:
        img = mirror(img)
    return img


