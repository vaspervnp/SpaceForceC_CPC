DRAWN = {'n': N, 'ne': NE, 'e': E}
# (πηγή, ανάποδα, καθρέφτης)
DERIVED = {
    's':  ('n',  True,  False),
    'se': ('ne', True,  False),
    'nw': ('ne', False, True),
    'sw': ('ne', True,  True),
    'w':  ('e',  False, True),
}

EARTH_TINT = {'D': 'b'}          # πτερύγια κενού -> εισαγωγές αέρα


def frame(direction, world='space'):
    if direction in DRAWN:
        img = art(DRAWN[direction], W, H, 'ship/' + direction)
    else:
        src, do_flip, do_mirror = DERIVED[direction]
        img = art(DRAWN[src], W, H, 'ship/' + src)
        if do_flip:
            img = flip(img)
        if do_mirror:
            img = mirror(img)
    if world == 'earth':
        img = recolour(img, {PEN[a]: PEN[b] for a, b in EARTH_TINT.items()})
    return img


def all_frames(world='space'):
    return [(d, frame(d, world)) for d in DIRS]
