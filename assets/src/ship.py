"""The Flying Patates — το πλοίο του Wing C. Κάτοψη, 8 κατευθύνσεις.

ΤΟ ΠΛΑΙΣΙΟ ΕΙΝΑΙ 12x24 PIXELS = 24x24 ΜΟΝΑΔΕΣ ΟΘΟΝΗΣ

Το design document λέει «24x24». Στο Mode 0 το pixel είναι ΔΙΠΛΑΣΙΑ ΦΑΡΔΥ από
ψηλό, οπότε 24x24 pixels θα ήταν 48x24 μονάδες — διπλάσια φαρδύ από ψηλό. Ένα
σκάφος που στρίβει και στις οκτώ κατευθύνσεις ΔΕΝ μπορεί να ζει σε τέτοιο
πλαίσιο: στραμμένο δεξιά θα χώραγε, στραμμένο πάνω θα κοβόταν στη μέση.

Άρα το «24x24» τηρείται ως 24x24 ΜΟΝΑΔΕΣ ΟΘΟΝΗΣ, που στο Mode 0 γράφεται
12x24 pixels. Το σκάφος βγαίνει τετράγωνο και ίδιο σε κάθε κατεύθυνση, και
πληρώνει 288 bytes/καρέ αντί για 576 — blit 1,6 ms αντί για 3,3.

ΤΡΕΙΣ ΖΩΓΡΑΦΙΖΟΝΤΑΙ, ΠΕΝΤΕ ΒΓΑΙΝΟΥΝ

Σε κάτοψη το σκάφος είναι συμμετρικό ΑΡΙΣΤΕΡΑ-ΔΕΞΙΑ ως προς τον άξονά του.
Άρα:

    ζωγραφισμένες   N   NE   E
    κατακόρυφη      S  = N  ανάποδα        SE = NE ανάποδα
    οριζόντια       W  = E  καθρέφτης      NW = NE καθρέφτης
    και τα δύο      SW = NE ανάποδα + καθρέφτης

Δεν είναι μόνο λιγότερη δουλειά, είναι ΕΓΓΥΗΣΗ: οι οκτώ όψεις δεν γίνεται να
ξεφύγουν η μία από την άλλη σε μέγεθος ή χρώμα, γιατί είναι το ίδιο σχέδιο.

Η ΔΙΑΓΩΝΙΟΣ ΔΕΝ ΕΙΝΑΙ ΣΤΙΣ 45 ΜΟΙΡΕΣ ΣΤΟ ΠΛΕΓΜΑ

Γραμμή που φαίνεται 45 μοίρες ΣΤΗΝ ΟΘΟΝΗ πηγαίνει 1 μονάδα δεξιά ανά 1 μονάδα
κάτω — δηλαδή ΜΙΣΟ pixel δεξιά ανά 1 pixel κάτω. Γι' αυτό το NE δεν είναι το N
γυρισμένο 45 μοίρες στο πλέγμα: είναι πολύ πιο όρθιο, και γέρνει μία στήλη ανά
δύο γραμμές.

Ο ΚΟΣΜΟΣ ΑΛΛΑΖΕΙ ΤΑ ΠΤΕΡΥΓΙΑ, ΟΧΙ ΤΗ ΣΙΛΟΥΕΤΑ

Στη Γη τα πορτοκαλί πτερύγια γίνονται ουρανί — εισαγωγές αέρα αντί για
ακροφύσια κενού. Η σιλουέτα μένει ίδια επίτηδες: είναι η ταυτότητα του
σκάφους, και αν άλλαζε ο παίκτης θα νόμιζε ότι του έδωσαν άλλο πλοίο.

Η ΦΛΟΓΑ ΔΕΝ ΕΙΝΑΙ ΜΕΣΑ ΣΤΟ SPRITE

Αν ήταν, κάθε κατεύθυνση θα χρειαζόταν 3 καρέ φλόγας: 8 x 3 x 2 κόσμους = 48
καρέ αντί για 16. Η φλόγα είναι ξεχωριστό 8x8 (δες `fx.py`) που μπαίνει στο
`FLAME_AT` της κατεύθυνσης, ΠΡΙΝ από το σκάφος ώστε να χώνεται από κάτω του.
Ο μαύρος καπνός της Γης είναι το ίδιο κόλπο, άλλο sprite.
"""
from gfx import PEN, art, flip, mirror, recolour

W, H = 12, 24

# Με τη σειρά του ρολογιού, από τον βορρά. Ο δείκτης είναι ΚΑΙ η γωνία x45.
