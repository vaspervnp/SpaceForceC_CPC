; palette.asm — τα 16 INK του Space Force C
; ΠΑΡΑΓΕΤΑΙ ΑΥΤΟΜΑΤΑ από assets/src/make_assets.py.
;
; Μία παλέτα για τους δύο κόσμους: το σκάφος, τα βλήματα, οι
; εκρήξεις, τα μυρμήγκια και το HUD εμφανίζονται και στις οκτώ
; πίστες. Αν τα pens άλλαζαν νόημα στη μέση, καθένα από αυτά θα
; χρειαζόταν δεύτερη έκδοση.
;
; Το pen 0 είναι ΔΙΑΦΑΝΟ στα sprites και μαύρο στα πλακίδια.

palette:
  db 0   ; pen 0  '.' Black           ΔΙΑΦΑΝΟ στα sprites, κενό διάστημα στα tiles
  db 1   ; pen 1  'K' Blue            περίγραμμα και βαθιά σκιά (περνάει για μαύρο)
  db 13  ; pen 2  'i' White           γκρι: μέταλλο, πέτρα, μάρμαρο σκιά
  db 26  ; pen 3  'I' Bright white    ανταύγεια, αστέρια, κείμενο
  db 3   ; pen 4  'd' Red             καφέ σκούρο: βαλίτσες, ρίζες, μυρμήγκια
  db 15  ; pen 5  'D' Orange          καφέ/πορτοκαλί: πτερύγια, σκουριά, φλόγα
  db 6   ; pen 6  'r' Bright red      κίνδυνος: εκρήξεις, σφραγίδα, boss
  db 24  ; pen 7  'y' Bright yellow   πυρήνας φλόγας, χρυσό, μπαγκέτα
  db 25  ; pen 8  'S' Pastel yellow   ΤΟ ΣΩΜΑ ΤΟΥ ΠΛΟΙΟΥ — πατάτα, κρεμ, μάρμαρο
  db 20  ; pen 9  'c' Bright cyan     θόλος πιλοτηρίου, ενέργεια, πάγος
  db 11  ; pen 10 'b' Sky blue        ψυχρό μέταλλο, ουρανός της Γης
  db 8   ; pen 11 'm' Bright magenta  neon του Disco-Ray, λάμψη power-up
  db 16  ; pen 12 'p' Pink            έντυπα Ε9, σάρκα, τουρίστες
  db 9   ; pen 13 'n' Green           πράσινο σκούρο: εξωγήινοι σκιά, βλάστηση
  db 18  ; pen 14 'g' Bright green    πράσινο φωτεινό: φτάρνισμα, εξωγήινοι
  db 12  ; pen 15 'o' Yellow          λαδί: σκουπίδια, σπαγγέτι, βρόμικο μέταλλο

; hardware values για OUT (#7F00), αν γράψεις δικό σου
; set-ink αντί για το firmware #BC32:
palette_hw:
  db #54,#44,#40,#4A,#5C,#4E,#4C,#4B,#43,#53,#57,#4D,#47,#56,#52,#5E
